// MATERIAL_OVERRIDES — точечные правки КОНКРЕТНЫХ материалов (ключ —
// точное имя материала, до \r-артикула, как в JSON/.b3d), сделанные
// через живой редактор материалов во вьювере (правая панель, кнопка
// "Сохранить в material_config.js"). В отличие от MATERIAL_TYPES (теперь
// в Fotly.html — правила для ЦЕЛОЙ категории вроде "ЛДСП") — тут правка
// ОДНОГО конкретного материала, и она перекрывает вообще всё остальное
// (категорию/БД/имя/пользовательские свойства) — самый высокий
// приоритет, т.к. это осознанный выбор человека именно для этого
// материала.
//
// Блок поддерживается АВТОМАТИЧЕСКИ вьювером — кнопка "Сохранить"
// каждый раз перезаписывает целиком то, что между маркерами ниже. Руками
// лучше не трогать форматирование (сами значения менять можно, вьювер
// прочитает как обычный JS-объект), но если нужно — поля у одной записи:
//   colorHex     "#rrggbb" — цвет (когда без своей текстуры)
//   textureFile  "u999.jpg" — ИМЯ файла текстуры, БЕЗ ПУТИ — сам файл
//                никуда не копируется, вьювер просто ищет его по имени
//                в уже подключённой папке материалов при следующей
//                загрузке; если имя не найдено — тихо остаётся то, что
//                нашла обычная автоматика (TexturePath/.dae/имя)
//   roughness/metalness/opacity/transparent — как в MATERIAL_TYPES
//                (теперь в Fotly.html)
//   homogeneous  true/false — "торец = пласть" (см. пояснение в Fotly.html)
// === MATERIAL_OVERRIDES: начало (автоматически поддерживается вьювером) ===
