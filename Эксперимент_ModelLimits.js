// ============================================================
// ЭКСПЕРИМЕНТ (не рабочий инструмент) — проверяем гипотезу: движок
// Базиса, возможно, определяет спецотрисовку "габаритной рамки" по
// "магической" строке MaterialName = "~$$$ModelLimits", а не по
// какому-то отдельному скрытому типу объекта.
//
// Строит ОБЫЧНЫЙ Extrusion (простой тестовый параллелепипед 300x300x300
// мм в углу модели) и пытается присвоить ему тот же MaterialName, что
// был у настоящей "габаритной рамки".
//
// Три возможных исхода — все информативны:
// 1) Присвоение MaterialName упадёт с ошибкой -> строка защищена,
//    гипотеза неверна, дальше копать в эту сторону не стоит.
// 2) Присвоение пройдёт, но объект в 3D-виде выглядит как обычная
//    сплошная деталь -> строка ни на что не влияет, просто текстовое
//    поле, гипотеза неверна.
// 3) Объект начнёт визуально/в дереве модели вести себя иначе, чем
//    обычный Extrusion (например, станет каркасным/невидимым для
//    экспорта и т.п.) -> гипотеза подтверждена, можно строить на этом.
//
// После проверки тестовый объект нужно удалить вручную (он ничем не
// помечен как временный специально, чтобы вы могли спокойно его
// разглядеть/покрутить перед удалением).
// ============================================================

try {
    var Ext = AddExtrusion('ЭКСПЕРИМЕНТ ModelLimits');
    StartEditing(Ext);
    Ext.Contour.AddRectangle(0, 0, 300, 300);
    Ext.Orient(AxisZ, AxisY);
    Ext.Thickness = 300;
    Ext.Build();

    var Msg = 'Объект построен как обычный Extrusion.\n';
    try {
        Ext.MaterialName = '~$$$ModelLimits';
        Msg += 'MaterialName присвоен без ошибки: "' + Ext.MaterialName + '".\n';
        Msg += 'Посмотрите на него в 3D-виде и в дереве модели — выглядит/ведёт себя как-то иначе, чем обычная деталь?';
    } catch (eSet) {
        Msg += 'Присвоить MaterialName не удалось: ' + eSet.message;
    }

    alert(Msg);

} catch (eTop) {
    alert('Ошибка эксперимента: ' + eTop.message);
}
