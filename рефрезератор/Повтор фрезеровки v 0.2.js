// ============================================================
// Фрезеровка "волна" — множество одинаковых пазов (канавок) с равным
// шагом по всей ширине/высоте панели, сразу на НЕСКОЛЬКИХ выделенных
// панелях. ДВА СПОСОБА на выбор в диалоге ("Способ"):
//   - "Раздельные пазы" — N отдельных объектов Cut, каждый своя прямая
//     траектория (см. applyWave ниже).
//   - "Змейка" — один непрерывный Cut на панель, ломаная траектория
//     проходит зубец-выход за край-шаг вбок за панелью-возврат-зубец
//     и т.д. (см. applySnakeWave ниже) — ближе к тому, как реально
//     работает ЧПУ-фреза (один проход, без отрыва), но Базис может
//     повести себя капризно на поворотах ломаной (см. комментарий у
//     applySnakeWave).
// Профиль паза (сечение фрезы) НЕ рисуется в самом скрипте —
// пользователь заранее делает ОДИН паз вручную на ПЕРВОЙ выделенной
// панели (образец, обычным способом через диалог Базиса), скрипт
// читает его Contour (сечение) и копирует на все нужные позиции всех
// выделенных панелей, включая саму первую.
//
// Как пользоваться:
//   1. На одной панели сделать один паз-образец вручную (нужная форма
//      сечения — полукруг/трапеция/что угодно, глубина настроена как
//      надо). Это и есть "контур фрезы".
//   2. Выделить эту панель ПЕРВОЙ, затем добавить к выделению остальные
//      панели, на которых нужна та же "волна" — ДО запуска скрипта.
//   3. Запустить скрипт, задать шаг/отступ/направление, нажать
//      "Применить".
//
// ВЫДЕЛЕНИЕ ЧИТАЕТСЯ ОДИН РАЗ, СРАЗУ ПРИ ЗАПУСКЕ (проверено на практике:
// пока открыт диалог свойств скрипта, Базис не даёт менять выделение в
// 3D-виде вообще — переделывать выделение "на лету" между нажатиями
// физически нельзя). Диалог при этом ОСТАЁТСЯ ОТКРЫТЫМ после
// "Применить" — по прямой просьбе пользователя ("скрипт не
// завершается") — это удобно, чтобы попробовать НЕСКОЛЬКО разных
// шаг/отступ/направление на ОДНОМ и том же выделении подряд, не
// перезапуская скрипт и не выделяя панели заново каждый раз. Закрыть —
// кнопка "Готово" (или просто Esc).
//
// ПОВТОРНЫЕ НАЖАТИЯ "Применить" НЕ ПЛОДЯТ ДУБЛИ — по прямой просьбе
// пользователя ("чтоб редактировались наши пазы, а не создавались
// дубликаты"): перед каждой перестройкой узора вызывается глобальная
// DeleteNewObjects() — штатный приём Базиса для "живого предпросмотра"
// (см. docs/Базис_справочник_для_Claude.md, "Action.Properties"), стирает
// ВСЁ, что этот же запуск скрипта успел построить с прошлого нажатия, и
// строит заново с текущими шаг/отступ/направление. Паз-образец, который
// сделал сам пользователь ДО запуска скрипта, этим не затрагивается —
// DeleteNewObjects трогает только то, что создано В ТЕКУЩЕМ действии.
// НЕ ПРОВЕРЕНО ЖИВЬЁМ конкретно на пазах (Cuts — это правка уже
// существующей панели, не новый top-level объект, как обычно
// подразумевает DeleteNewObjects в документации) — если после
// "Применить" второй раз пазы всё-таки задваиваются, значит на Cuts это
// не работает, дальше придётся разбираться отдельно.
//
// ВАЖНО: удалить образец-паз через скрипт НЕЛЬЗЯ (у Panel.Cuts, как и у
// Butts/Plastics — та же схема в официальном API, есть только Add(), без
// Remove/Delete). Вместо удаления скрипт узнаёт ПОЗИЦИЮ образца (по его
// же Trajectory) и просто НЕ создаёт новый паз в этом же месте на первой
// панели — образец сам становится "своим" пазом узора, дублей не будет.
// На остальных панелях выделения (где своего паза ещё нет) генерируется
// полный узор без пропусков.
//
// Профиль паза копируется В ТОЧНОСТИ как нарисован на образце (те же
// координаты по толщине панели) — годится, только если у всех
// выделенных панелей ОДИНАКОВАЯ толщина, что и у панели-образца.
// ============================================================

// Позиция образца-паза вдоль оси шага (X — для вертикальных бороздок,
// Y — для горизонтальных), по его собственной Trajectory (первый
// элемент, обычная линия — так строит и сам скрипт, и обычный паз
// руками в Базисе). null, если разобрать не удалось (тогда просто не
// пропускаем ни одну позицию — старое поведение, ничего не ломаем).
function getSamplePositionAlongAxis(cut, vertical) {
  if (!cut.Trajectory || cut.Trajectory.Count === 0) return null;
  var e = cut.Trajectory.Objects[0];
  if (!e.IsLine()) return null;
  var l = e.AsLine();
  return vertical ? l.Pos1.x : l.Pos1.y;
}

// Копирует геометрию сечения паза (src) в только что созданный,
// изначально пустой Contour2D (dst) — элемент за элементом, других
// способов клонировать Contour2D в скриптовом API нет. Эллипсы и
// вложенные списки внутри профиля фрезы — редкий случай для сечения
// паза, не поддержаны (профиль обычно линии+дуги).
function copyContour(src, dst) {
  for (var i = 0; i < src.Count; i++) {
    var e = src.Objects[i];
    if (e.IsLine()) {
      var l = e.AsLine();
      dst.AddLine(l.Pos1.x, l.Pos1.y, l.Pos2.x, l.Pos2.y);
    } else if (e.IsArc()) {
      var a = e.AsArc();
      dst.AddArc(
        { x: a.Pos1.x, y: a.Pos1.y },
        { x: a.Pos2.x, y: a.Pos2.y },
        { x: a.Center.x, y: a.Center.y },
        a.ArcDir
      );
    } else if (e.IsCircle()) {
      var c = e.AsCircle();
      dst.AddCircle(c.Center.x, c.Center.y, c.CirRadius);
    }
    // эллипс/вложенный список — пропускаем молча, для сечения фрезы
    // это практически не встречается
  }
}

// panels — снимок выделения, сделанный ОДИН РАЗ при запуске скрипта
// (см. комментарий в шапке файла — менять выделение, пока открыт
// диалог, нельзя, поэтому и не перечитываем).
function applyWave(panels, step, margin, vertical) {
  var sampleCut = panels[0].Cuts.Cuts[0];
  var sampleContour = sampleCut.Contour;

  // Считаем позицию образца ОДИН РАЗ, по актуальному направлению из
  // диалога (пользователь мог поменять направление уже после того,
  // как образец был нарисован в другой ориентации — сравниваем всё
  // равно по той оси, что выбрана сейчас, это осознанный выбор: раз
  // направление выбрано явно, узор должен идти именно по нему).
  var samplePos = getSamplePositionAlongAxis(sampleCut, vertical);
  var skippedForSample = 0;

  var totalCuts = 0;
  for (var p = 0; p < panels.length; p++) {
    var panel = panels[p];
    StartEditing(panel);

    // Реальные границы контура панели (Min/Max), НЕ предположение
    // "всегда от (0,0)" — по жалобе пользователя: у зеркальной копии
    // панели локальный контур может лежать в другом диапазоне (не
    // от нуля), и пазы, посчитанные от (0,0), рисовались "в воздухе"
    // мимо настоящего материала.
    var minX = panel.Contour.Min.x, minY = panel.Contour.Min.y;
    var maxX = panel.Contour.Max.x, maxY = panel.Contour.Max.y;
    var W = maxX - minX, H = maxY - minY;
    var span = vertical ? W : H;

    var index = 1;
    for (var offset = margin; offset <= span - margin + 1e-6; offset += step) {
      var pos = vertical ? (minX + offset) : (minY + offset);
      // Пропускаем позицию образца ТОЛЬКО на самой первой панели
      // (p===0) — это она уже имеет готовый паз-образец, остальные
      // панели выделения своего паза ещё не имеют, им нужен полный
      // узор без пропусков.
      if (p === 0 && samplePos !== null && Math.abs(pos - samplePos) < step / 2) {
        skippedForSample++;
        index++;
        continue;
      }
      var cut = panel.AddCut('Волна ' + index);
      if (vertical) {
        cut.Trajectory.AddLine(pos, minY, pos, maxY);
      } else {
        cut.Trajectory.AddLine(minX, pos, maxX, pos);
      }
      copyContour(sampleContour, cut.Contour);
      index++;
      totalCuts++;
    }

    panel.Build();
  }

  // Короткий alert — по прямой просьбе пользователя ("для людей других
  // это лишнее"): подробности (пропуск позиции образца и т.п.) остаются
  // только в комментариях кода, наружу — просто "готово" и итоговые
  // цифры.
  alert('Готово: панелей — ' + panels.length + ', пазов — ' + totalCuts + '.');
}

// ============================================================
// Способ "Змейка" — ОДИН непрерывный паз на панель вместо N отдельных:
// вдоль зубца, короткий выход центра фрезы за край панели, шаг вбок
// ЦЕЛИКОМ за пределами панели, возврат на панель, следующий зубец в
// обратную сторону — и так далее. Сечение (Contour) образца одно и то
// же на всём протяжении, включая повороты.
//
// Проверено пользователем на реальной панели (2026-09-02): лишних
// пауз/лагов Базиса это не убрало, плюс сам Базис из-за наложений на
// поворотах ломаной решил перестроить геометрию криво (артефакт на
// панели) — по словам пользователя, дело в поведении самого Базиса
// при наложениях, не в порочности самой идеи змейки. Оставлено вторым
// режимом на выбор — если наложений/артефактов у тебя на практике не
// будет, этот способ даёт вместо кучи объектов "Волна N" один паз на
// панель.
//
// УПРОЩЕНИЕ (в отличие от "раздельных пазов" выше): образец-паз НЕ
// встраивается в змейку — на первой панели, скорее всего, получится
// ещё и отдельный паз-образец рядом/поверх одного из зубцов.
// ============================================================
function applySnakeWave(panels, step, margin, overtravel, vertical) {
  var sampleContour = panels[0].Cuts.Cuts[0].Contour;

  var totalPanels = 0;
  for (var p = 0; p < panels.length; p++) {
    var panel = panels[p];
    StartEditing(panel);

    var minX = panel.Contour.Min.x, minY = panel.Contour.Min.y;
    var maxX = panel.Contour.Max.x, maxY = panel.Contour.Max.y;
    var W = maxX - minX, H = maxY - minY;
    var span = vertical ? W : H;          // ось шага (поперёк зубцов)
    var alongMin = vertical ? minY : minX; // ось самого зубца (вдоль)
    var alongMax = vertical ? maxY : maxX;

    var positions = [];
    for (var offset = margin; offset <= span - margin + 1e-6; offset += step) {
      positions.push((vertical ? minX : minY) + offset);
    }
    if (positions.length === 0) { panel.Build(); continue; }

    function toXY(along, across) {
      return vertical ? { x: across, y: along } : { x: along, y: across };
    }

    var cut = panel.AddCut('Волна-змейка');
    copyContour(sampleContour, cut.Contour);
    var traj = cut.Trajectory;

    function addSeg(a1, c1, a2, c2) {
      var p1 = toXY(a1, c1), p2 = toXY(a2, c2);
      traj.AddLine(p1.x, p1.y, p2.x, p2.y);
    }

    var goingUp = true;
    for (var i = 0; i < positions.length; i++) {
      var c = positions[i];
      var aFrom = goingUp ? alongMin : alongMax;
      var aTo = goingUp ? alongMax : alongMin;
      addSeg(aFrom, c, aTo, c);

      if (i < positions.length - 1) {
        var cNext = positions[i + 1];
        var aOut = aTo + (goingUp ? overtravel : -overtravel);
        addSeg(aTo, c, aOut, c);
        addSeg(aOut, c, aOut, cNext);
        addSeg(aOut, cNext, aTo, cNext);
      }
      goingUp = !goingUp;
    }

    panel.Build();
    totalPanels++;
  }

  alert('Готово: панелей — ' + totalPanels + ', на каждой один паз-змейка.');
}

try {

  // Выделение — СНИМОК на момент запуска (см. большой комментарий в
  // шапке файла про то, почему не читаем заново на каждое "Применить").
  var panels = [];
  for (var i = 0; i < Model.SelectionCount; i++) {
    var obj = Model.Selections[i];
    if (obj && obj.AsPanel) panels.push(obj.AsPanel);
  }

  if (panels.length === 0) {
    alert('Ничего не выделено. Выдели панели ДО запуска скрипта: первой — ту, где уже есть паз-образец, дальше — остальные для "волны".');
  } else if (!panels[0].Cuts || panels[0].Cuts.Count === 0) {
    alert('На ПЕРВОЙ выделенной панели нет ни одного паза. Сначала сделай на ней один паз вручную — его сечение (профиль фрезы) станет образцом для всех остальных.');
  } else {

    var Prop = Action.Properties;
    var ModeProp = Prop.NewCombo('Способ', 'Змейка (один сплошной паз)\nРаздельные пазы');
    ModeProp.ItemIndex = 0;
    var StepProp = Prop.NewNumber('Шаг между пазами, мм', 20);
    var MarginProp = Prop.NewNumber('Отступ от края, мм', 0);
    var OvertravelProp = Prop.NewNumber('Выход фрезы за край (только для змейки), мм', 10);
    var DirProp = Prop.NewCombo('Направление бороздок', 'Вертикально (сверху вниз)\nГоризонтально (слева направо)');
    DirProp.ItemIndex = 0;
    var ApplyBtn = Prop.NewButton('Применить');
    var DoneBtn = Prop.NewButton('Готово');

    Prop.NewSeparator();
    Prop.NewLabel('Автор: Виталий Ястов');
    Prop.NewLabel('Сайт: boosty.to/vetalyty');

    // Общая пересборка для обеих кнопок — "Готово" тоже честно строит по
    // ТЕКУЩИМ значениям диалога перед тем, как зафиксировать (тот же
    // канонический приём "живого предпросмотра", что и в справочнике —
    // см. большой комментарий в шапке файла), а не полагается на то, что
    // пользователь обязательно нажал "Применить" перед "Готово".
    // Возвращает true, если пересборка прошла (можно фиксировать/
    // закрывать), false — если параметры некорректны (и уже показан
    // alert с причиной, закрывать диалог в этом случае не нужно).
    function rebuild() {
      // +0.1мм принудительно поверх того, что ввёл пользователь — по
      // прямой просьбе: даже если в поле написано ровно 20, реальный шаг
      // между соседними зубцами должен быть 20.1, не 20.0 ровно (небольшой
      // гарантированный зазор между соседними пазами, не впритык).
      var step = StepProp.Value + 0.1;
      var margin = MarginProp.Value;
      var overtravel = OvertravelProp.Value;
      var vertical = (DirProp.ItemIndex === 0);
      var snake = (ModeProp.ItemIndex === 0);

      if (!(step > 0)) {
        alert('Шаг между пазами должен быть больше 0.');
        return false;
      }
      if (snake && !(overtravel >= 0)) {
        alert('Выход фрезы за край не может быть отрицательным.');
        return false;
      }

      try {
        // Стираем то, что этот же запуск скрипта построил в прошлый раз
        // (если это первый вызов — стирать нечего, тоже нормально), и
        // строим заново с текущими параметрами — по прямой просьбе:
        // чтобы редактировался один и тот же узор, а не копился дублями.
        DeleteNewObjects();
        if (snake) applySnakeWave(panels, step, margin, overtravel, vertical);
        else applyWave(panels, step, margin, vertical);
        return true;
      } catch (e) {
        alert('Ошибка: ' + e.message);
        return false;
      }
    }

    // Само сохранение в модель (Action.Commit) — ТОЛЬКО по кнопке
    // "Готово", не по "Применить", по прямой просьбе пользователя
    // ("после кнопки готово применялась фрезеровка") — "Применить" лишь
    // показывает предпросмотр узора, ничего не фиксирует окончательно.
    ApplyBtn.OnClick = function () { rebuild(); };

    DoneBtn.OnClick = function () {
      if (!rebuild()) return; // параметры некорректны — диалог остаётся открытым, alert уже показан
      Action.Commit();
      Action.Finish();
    };

    Action.Continue();
  }

} catch (e) {
  alert('Ошибка: ' + e.message);
}
